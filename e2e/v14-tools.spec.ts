  test('noise-remover processes audio via ffmpeg', async ({ page }) => {
    test.setTimeout(60000);
    await page.goto('/tools/noise-remover');
    await page.evaluate(async () => {
      const sr = 8000, n = sr;
      const buf = new ArrayBuffer(44 + n * 2);
      const v = new DataView(buf);
      const wr = (o: number, s: string) => { for (let i = 0; i < s.length; i++) v.setUint8(o + i, s.charCodeAt(i)); };
      wr(0,'RIFF'); v.setUint32(4, 36+n*2, true); wr(8,'WAVE'); wr(12,'fmt ');
      v.setUint32(16,16,true); v.setUint16(20,1,true); v.setUint16(22,1,true);
      v.setUint32(24,sr,true); v.setUint32(28,sr*2,true); v.setUint16(32,2,true); v.setUint16(34,16,true);
      wr(36,'data'); v.setUint32(40,n*2,true);
      const file = new File([buf], 'noisy.wav', { type: 'audio/wav' });
      const dt = new DataTransfer(); dt.items.add(file);
      const input = document.getElementById('fileInput') as HTMLInputElement;
      input.files = dt.files;
      input.dispatchEvent(new Event('change', { bubbles: true }));
    });
    await page.click('#actionBtn');
    await page.waitForFunction(() => {
      const s = document.getElementById('status')?.textContent || '';
      return s.includes('reduced') || s.toLowerCase().includes('error');
    }, { timeout: 50000 });
    const status = await page.locator('#status').textContent() || '';
    if (!status.includes('reduced')) console.log('noise-remover note:', status);
  });

